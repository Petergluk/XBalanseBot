DEFAULT_GIDE_TEXT = """
📜 <b>Руководство для Администратора</b>

Этот бот управляет внутренней экономикой сообщества. Вот ключевые концепции:

<b>1. Пользователи и Баланс:</b>
- Каждый участник группы, запустивший бота, имеет свой баланс в <b>{currency_symbol}</b>.
- Команда <code>/check @username</code> позволяет увидеть полную информацию о пользователе.

<b>2. Активности (Activities):</b>
- Это долгосрочные направления деятельности (кружки, группы, проекты). Например, "Йога" или "Книжный клуб".
- Пользователи могут <b>подписываться</b> на активности (<code>/activity</code>), чтобы участвовать в связанных с ними событиях.
- Команды: <code>/create_act</code>, <code>/edit_act</code>, <code>/delete_act</code>.

<b>3. События (Events):</b>
- Это конкретные мероприятия с датой и стоимостью. Событие может быть привязано к активности или быть общим для всех.
- <b>Типы событий:</b>
    - <u>Разовое</u>: Происходит один раз в указанную дату и время.
    - <u>Регулярное</u>: Повторяется по правилу (например, "каждый вторник в 19:00").
- При наступлении события с подписчиков автоматически списывается плата.
- Команды: <code>/create_event</code>, <code>/edit_event</code>, <code>/delete_event</code>.

<b>4. Демередж (Demurrage):</b>
- Механизм "отрицательного процента на остаток". Если включен, ежедневно с баланса каждого пользователя списывается небольшой процент в общий фонд.
- Стимулирует оборот средств, а не их накопление.
- Команды: <code>/demurrage_on</code>, <code>/demurrage_off</code>, <code>/set_demurrage</code>.

<b>5. Фонд Сообщества:</b>
- Это специальный системный пользователь (<code>@fund</code>), на счет которого поступают средства от демерреджа и других системных операций.
- Пользователи могут добровольно пополнять фонд командой <code>/send @fund сумма</code>.
- Из фонда можно делать выплаты пользователям (<code>/pay_from_fund</code>), например, за волонтерскую работу.

<b>6. Welcome-бонус:</b>
- Сумма, которая автоматически начисляется новому пользователю при первом запуске бота (<code>/start</code>) или при вступлении в группу.
- Команда: <code>/welcome_bonus [сумма]</code>.

<b>Ваши основные задачи:</b>
- Создавать и поддерживать актуальность активностей и событий.
- Отвечать на вопросы пользователей.
- Управлять системными настройками (демередж, курс обмена).
- Модерировать экономику: делать начисления (<code>/add</code>), списания (<code>/rem</code>) и выплаты из фонда.
"""

